import kotlin.reflect.KClass

@PageContractsDsl
sealed class PageContract {
    abstract var title: String?

    @PageExtensionImplementationApi
    abstract fun <T : AbstractPageExtension<*>> extend(kClass: KClass<T>, value: T)

    inline fun <reified T : AbstractPageExtensionVoid> extend(value: T) {
        @OptIn(PageExtensionImplementationApi::class)
        extend(T::class, value)
    }

    inline fun <reified T : AbstractPageExtension<C>, C> extend(
        value: T,
        noinline cfg: C.() -> Unit
    ) {
        @OptIn(PageExtensionImplementationApi::class)
        extend(T::class, value.also { it.configure(this, cfg) })
    }

    inline fun <reified T : AbstractPageExtensionVoid> extend(value: () -> T) {
        @OptIn(PageExtensionImplementationApi::class)
        extend(T::class, value())
    }

    inline fun <reified T : AbstractPageExtension<C>, C> extend(
        value: () -> T,
        noinline cfg: C.() -> Unit
    ) {
        @OptIn(PageExtensionImplementationApi::class)
        extend(T::class, value().also { it.configure(this, cfg) })
    }
}

interface StatusDetail {
    data object Empty : StatusDetail {
        override fun toString(): String {
            return "<no details>"
        }
    }
}

@PageContractsDsl
abstract class PageInit {
    abstract suspend fun halt(detail: StatusDetail = StatusDetail.Empty): Nothing
}

@OptIn(ExperimentalContracts::class)
val PageInit.server: Boolean
    get() {
        contract {
            returns(true) implies (this@server is PageServerInit)
        }

        return this is PageServerInit
    }

@PageContractsDsl
abstract class PageServerInit : PageInit() {
    abstract suspend fun respond(status: HttpStatus, detail: StatusDetail = StatusDetail.Empty): Nothing

    override suspend fun halt(detail: StatusDetail): Nothing =
        respond(HttpStatus.INTERNAL_SERVER_ERROR, detail)
}

@OptIn(ExperimentalContracts::class)
val PageInit.client: Boolean
    get() {
        contract {
            returns(true) implies (this@client is PageClientInit)
        }

        return this is PageClientInit
    }

/**
 * This function can be used to define additional metadata for pages in code.
 * The lambda you pass here will be "pulled" out from the function and called
 * before your [@Page][net.derfruhling.serenity.annotations.Page] function ever
 * runs. Despite this, you can still use parameters, **but you cannot use other
 * local variables!**
 *
 * The local function generated by the compiler when you call this function
 * will get moved into the resulting [PageHolder] class, with all parameter
 * references replaced with property getter calls as appropriate.
 * To denote this behavior, the lambda type has been annotation with
 * [@PromotedLambda][PromotedLambda].
 *
 * As such, if you call this function, it should be the first thing called
 * in the whole [@Page][net.derfruhling.serenity.annotations.Page].
 */
@Intrinsic
@OptIn(ExperimentalContracts::class)
fun pageContract(fn: @PromotedLambda @DisallowComposableCalls PageContract.() -> Unit) {
    @Suppress("WRONG_INVOCATION_KIND")
    contract {
        callsInPlace(fn, kind = InvocationKind.EXACTLY_ONCE)
    }

    throw NotImplementedError()
}

@Intrinsic
@OptIn(ExperimentalContracts::class)
